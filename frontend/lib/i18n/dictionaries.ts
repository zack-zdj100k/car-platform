/** Merges a locale over English so a missing string never renders blank. */
function mergeDictionary(locale: Locale): Dictionary {
  if (locale === 'en') return en;
  const overlay = DICTIONARIES[locale];
  const result = {} as Record<string, Record<string, string>>;

  for (const [section, strings] of Object.entries(en)) {
    const overlaySection = (overlay as Record<string, Record<string, string> | undefined>)[section];
    result[section] = { ...(strings as Record<string, string>), ...(overlaySection ?? {}) };
  }

  return result as unknown as Dictionary;
}

const CACHE = new Map<Locale, Dictionary>();

export function getDictionary(locale: Locale): Dictionary {
  const cached = CACHE.get(locale);
  if (cached) return cached;
  const dictionary = mergeDictionary(locale);
  CACHE.set(locale, dictionary);
  return dictionary;
}

/** Replaces {placeholders} in a translated string. */
export function interpolate(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    key in values ? String(values[key]) : match,
  );
}
