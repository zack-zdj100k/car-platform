const BY_LOCALE: Record<Locale, Record<SpecKey, string>> = { en, fr, ar };

/** Every specification label, in the reader's language. */
export function specLabels(locale: Locale): Record<SpecKey, string> {
  return BY_LOCALE[locale] ?? en;
}

